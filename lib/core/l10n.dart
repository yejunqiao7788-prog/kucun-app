/// 四语 + 兜底 uk。索引顺序与 [kLangOrder] 一致。
class L10n {
  const L10n(this.lang);

  final String lang;

  static const String fallbackLang = 'uk';

  int get _index {
    final int position = kLangOrder.indexOf(lang);
    return position < 0 ? 2 : position;
  }

  static L10n of(Locale? locale) {
    final String code = locale?.languageCode ?? fallbackLang;
    return L10n(kLangOrder.contains(code) ? code : fallbackLang);
  }

  static List<Locale> get supportedLocales =>
      kLangOrder.map((String code) => Locale(code)).toList(growable: false);

  Locale get locale => Locale(lang);

  String raw(String key) {
    final List<String>? row = kStrings[key];
    if (row == null) return key;
    final int index = _index;
    final String value = index < row.length ? row[index] : row[2];
    return value.isEmpty ? key : value;
  }

  String fill(String key, Map<String, Object> args) {
    String value = raw(key);
    args.forEach((String name, Object arg) {
      value = value.replaceAll('{$name}', '$arg');
    });
    return value;
  }

  /// 相对时间：数值来自 [Fmt.elapsed]，单位词与语序由本表决定。
  String elapsed(DateTime? moment) {
    final ({int value, RelUnit unit}) parts = Fmt.elapsed(moment);
    switch (parts.unit) {
      case RelUnit.now:
        return raw('rel_now');
      case RelUnit.minute:
        return fill('rel_minutes', <String, Object>{'n': parts.value});
      case RelUnit.hour:
        return fill('rel_hours', <String, Object>{'n': parts.value});
      case RelUnit.day:
        return fill('rel_days', <String, Object>{'n': parts.value});
      case RelUnit.date:
        return Fmt.date(moment);
    }
  }

  String languageLabel(String code) {
    switch (code) {
      case 'zh':
        return '简体中文';
      case 'en':
        return 'English';
      case 'uk':
        return 'Українська';
      case 'vi':
        return 'Tiếng Việt';
      default:
        return code;
    }
  }

